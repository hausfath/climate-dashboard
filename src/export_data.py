_MODEL_BASELINES = ("1850-1900", "1951-1980", "1961-1990",
                    "1971-2000", "1981-2010")
_OBS_COLS = ["hadcrut5", "gistemp", "noaa", "berkeley", "copernicus"]
_OBS_TITLES = {"hadcrut5": "HadCRUT5", "gistemp": "GISTEMP", "noaa": "NOAA",
               "berkeley": "Berkeley Earth", "copernicus": "ERA5 (C3S)"}


def baseline_slug(baseline: str) -> str:
    return baseline.replace("-", "_")


def export_models_timeseries(cmip_df, obs_df, gen: str,
                             baseline: str) -> None:
    """Models-vs-obs scorecard: monthly ensemble stats + the five
    observational records on the selected baseline."""
    from src.models_vs_obs import compute_ensemble_stats, scenario_for

    bl_start, bl_end = (int(x) for x in baseline.split("-"))
    stats = compute_ensemble_stats(cmip_df, baseline_start=bl_start,
                                   baseline_end=bl_end)
    stats = stats[(stats["date"].dt.year >= 1900) &
                  (stats["date"].dt.year <= 2040)]

    obs = obs_df.copy()
    if baseline != "1850-1900":
        m = ((obs["date"].dt.year >= bl_start) &
             (obs["date"].dt.year <= bl_end))
        for c in _OBS_COLS:
            if c in obs.columns:
                bl_mean = obs.loc[m, c].mean()
                if not np.isnan(bl_mean):
                    obs[c] = obs[c] - bl_mean

    out = stats[["date", "mean", "p05", "p95"]].rename(
        columns={"mean": "model_mean_c", "p05": "model_p05_c",
                 "p95": "model_p95_c"})
    obs_cols = [c for c in _OBS_COLS if c in obs.columns]
    out = out.merge(obs[["date"] + obs_cols], on="date", how="left")
    out["obs_median_c"] = out[obs_cols].median(axis=1)
    out["date"] = out["date"].dt.strftime("%Y-%m-%d")

    gen_label = gen.upper()
    _write(out, f"models_timeseries_{gen}_{baseline_slug(baseline)}.csv",
           f"Climate models vs observations — {gen_label} "
           f"({scenario_for(gen)}), baseline {baseline}",
           [f"Monthly means, all series referenced to {baseline}. "
            "model_mean/p05/p95: ensemble mean and 5th-95th percentile "
            "across members.",
            "Observation columns: " + ", ".join(
                _OBS_TITLES[c] for c in obs_cols) + ".",
            "The dashboard's 12-month view is a 12-month rolling mean of "
            "these monthly columns."], float_format="%.4f")


def export_models_trends(cmip_df, obs_df, gen: str) -> None:
    """Warming trend by start year."""
    from src.models_vs_obs import (compute_variable_start_trends,
                                   scenario_for)

    data = compute_variable_start_trends(cmip_df, obs_df)
    out = pd.DataFrame({"start_year": data["start_years"],
                        "model_mean": data["model_mean"],
                        "model_p05": data["model_p05"],
                        "model_p95": data["model_p95"]})
    for c in _OBS_COLS:
        if f"obs_{c}" in data:
            out[c] = data[f"obs_{c}"]
    obs_cols = [c for c in _OBS_COLS if c in out.columns]
    out["obs_median"] = out[obs_cols].median(axis=1)

    gen_label = gen.upper()
    _write(out, f"models_trends_{gen}.csv",
           f"Warming trend by start year (to present) — {gen_label} "
           f"({scenario_for(gen)})",
           ["OLS trends in degC per decade from each start year through the "
            "latest observed month; model columns are the ensemble mean and "
            "5th-95th percentile across members.",
            "Trends are baseline-independent."], float_format="%.4f")


def export_models_trend_members(cmip_df, obs_df, gen: str) -> None:
    """Trend histograms: per-member trends for the three fixed windows."""
    from src.models_vs_obs import (_trend_cdecade, calculate_obs_trends,
                                   scenario_for)

    last_obs = obs_df["date"].max()
    end = last_obs.strftime("%Y-%m-%d")
    periods = [("1970-01-01", "1970-present"),
               ("2001-01-01", "2001-present"),
               ("2011-01-01", "2011-present")]
    ens_cols = [c for c in cmip_df.columns if c.startswith("ens_")]

    rows = []
    for start, label in periods:
        sub = cmip_df[(cmip_df["date"] >= start) & (cmip_df["date"] <= end)]
        for col in ens_cols:
            s = sub[col].dropna()
            if len(s) < 12:
                continue
            rows.append({"period": label, "source": "model_member",
                         "name": col.replace("ens_", "", 1),
                         "trend_c_per_decade":
                             _trend_cdecade(sub.loc[s.index, "date"], s)})
        for c, v in calculate_obs_trends(obs_df, start, end).items():
            if v is not None:
                rows.append({"period": label, "source": "observed",
                             "name": _OBS_TITLES.get(c, c),
                             "trend_c_per_decade": v})

    gen_label = gen.upper()
    _write(pd.DataFrame(rows), f"models_trend_members_{gen}.csv",
           f"Per-member warming trends for three windows — {gen_label} "
           f"({scenario_for(gen)})",
           ["OLS trends in degC per decade through the latest observed "
            "month; source distinguishes individual model ensemble members "
            "from the five observational records.",
            "These are the values binned in the dashboard's trend "
            "histograms."], float_format="%.4f")


