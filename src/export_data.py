def export_timeseries(df: pd.DataFrame) -> None:
    """Main timeseries panel: daily + annual files, each with observed and
    ENSO-removed columns (covers all four toggle states with two files)."""
    from src.dashboard import adjust_anomalies_to_preindustrial
    from src.enso_removal import remove_enso

    adj = adjust_anomalies_to_preindustrial(df).sort_values("date")
    rm = remove_enso(adj)

    daily = pd.DataFrame({
        "date": adj["date"].dt.strftime("%Y-%m-%d"),
        "anomaly_c": adj["anomaly"].values,
        "anomaly_enso_removed_c": rm["anomaly"].values,
        "rolling_365d_c": adj["anomaly"].rolling(365, center=True).mean().values,
        "rolling_365d_enso_removed_c":
            rm["anomaly"].rolling(365, center=True).mean().values,
    })
    _write(daily, "timeseries_daily.csv",
           "Daily global mean surface temperature anomaly (ERA5, 1940-present)",
           ["Anomalies vs preindustrial 1850-1900 (ERA5 1991-2020 climatology "
            "plus monthly preindustrial offsets).",
            "ENSO-removed columns subtract the lagged-ONI ENSO component "
            "(~0.1 degC per unit ONI at ~3-month lag); trend untouched.",
            "rolling_365d columns are 365-day centered means.",
            "Source: ECMWF ERA5 via Copernicus Climate Pulse."])

    cur_year = int(adj["date"].dt.year.max())
    g = adj.groupby(adj["date"].dt.year)["anomaly"].agg(["mean", "size"])
    g_rm = rm.groupby(rm["date"].dt.year)["anomaly"].mean()
    annual = pd.DataFrame({
        "year": g.index.astype(int),
        "annual_mean_c": g["mean"].values,
        "annual_mean_enso_removed_c": g_rm.reindex(g.index).values,
        "n_days": g["size"].astype(int).values,
    })
    annual["status"] = np.where(annual["year"] == cur_year, "year_to_date",
                                np.where(annual["n_days"] >= 360,
                                         "complete", "partial"))
    _write(annual, "timeseries_annual.csv",
           "Annual global mean surface temperature anomaly (ERA5)",
           ["Calendar-year means of the daily anomalies vs preindustrial "
            "1850-1900; the current year is a year-to-date mean.",
            "ENSO-removed column as in timeseries_daily.csv.",
            "Source: ECMWF ERA5 via Copernicus Climate Pulse."])


def export_year_context(df: pd.DataFrame) -> None:
    """'The year in context' panel: era envelopes + highlighted years
    (+ the EC46 forecast tail on the anomaly variant)."""
    from src.dashboard import (ERA_BANDS, THEME_CONFIG, _ec46_anomalize,
                               _load_ec46_forecast,
                               adjust_anomalies_to_preindustrial)

    years_hl = sorted(THEME_CONFIG["light"]["highlight_colors"])
    adj = adjust_anomalies_to_preindustrial(df)

    for mode, data, col in (("anomaly", adj, "anomaly"),
                            ("absolute", df, "temperature")):
        out = pd.DataFrame(index=pd.RangeIndex(1, 367, name="day_of_year"))
        for start, end in ERA_BANDS:
            era = data[(data["year"] >= start) & (data["year"] <= end)]
            grouped = era.groupby("day_of_year")[col]
            out[f"era_{start}_{end}_p05"] = (grouped.quantile(0.05)
                .rolling(7, center=True, min_periods=1).mean())
            out[f"era_{start}_{end}_p95"] = (grouped.quantile(0.95)
                .rolling(7, center=True, min_periods=1).mean())
        for year in years_hl:
            yd = data[data["year"] == year]
            out[str(year)] = yd.set_index("day_of_year")[col]

        notes = [
            "Rows are day-of-year; era columns are the 5th/95th percentile "
            "envelope per era (7-day smoothed); year columns are the "
            "highlighted recent years.",
            ("Anomalies vs preindustrial 1850-1900." if mode == "anomaly"
             else "Absolute global mean 2m temperature."),
            "Source: ECMWF ERA5 via Copernicus Climate Pulse."]

        if mode == "anomaly":
            try:
                ec46 = _load_ec46_forecast()
                fc = _ec46_anomalize(ec46, adj) if ec46 is not None else None
            except Exception:
                fc = None
            if fc is not None and not fc.empty:
                fc = fc.copy()
                fc["day_of_year"] = fc["date"].dt.dayofyear
                fc = fc.set_index("day_of_year")
                for src_col, dst in (("t2m_mean", "ec46_mean"),
                                     ("t2m_p5", "ec46_p05"),
                                     ("t2m_p25", "ec46_p25"),
                                     ("t2m_p75", "ec46_p75"),
                                     ("t2m_p95", "ec46_p95")):
                    out[dst] = fc[src_col]
                notes.insert(2, "ec46_* columns: ECMWF EC46 46-day forecast "
                             "(ensemble mean and percentiles), bias-corrected "
                             "and expressed as the same preindustrial anomaly.")
        _write(out.reset_index(), f"year_context_{mode}.csv",
               f"Recent years vs the historical range — daily "
               f"{'anomalies' if mode == 'anomaly' else 'absolute temperatures'}"
               " by day of year (ERA5)", notes)


def export_monthly_projection(df: pd.DataFrame) -> None:
    """Monthly projection panel: historical means for the current month plus
    the month-to-date value and the projection (EC46 blend, or the
    regression fallback — the method is recorded in the file)."""
    from src.dashboard import (adjust_anomalies_to_preindustrial,
                               get_monthly_projection)

    adj = adjust_anomalies_to_preindustrial(df)
    latest = adj["date"].max()
    month, year = latest.month, latest.year
    month_name = latest.strftime("%B")

    proj = get_monthly_projection(adj)
    pred = proj.get("prediction")
    mtd = proj.get("mtd_avg")

    md = adj[adj["date"].dt.month == month]
    monthly = md.groupby(md["date"].dt.year)["anomaly"].mean()

    out = pd.DataFrame({"year": monthly.index.astype(int),
                        "monthly_mean_c": monthly.values})
    out.loc[out["year"] == year, "monthly_mean_c"] = np.nan
    cur = out["year"] == year
    out["month_to_date_c"] = np.where(cur, mtd, np.nan)
    out["projected_c"] = np.where(cur, pred, np.nan)
    for k, col in (("lo95", "projection_p05_c"), ("lo50", "projection_p25_c"),
                   ("hi50", "projection_p75_c"), ("hi95", "projection_p95_c")):
        out[col] = np.where(cur, proj.get(k, np.nan), np.nan)
    out["method"] = np.where(cur, proj.get("method", ""), "")

    if proj.get("method") == "ec46_blend":
        method_note = (
            f"Projection: median and calibrated quantiles of the ECMWF EC46 "
            f"46-day ensemble ({proj.get('n_members', '?')} members, init "
            f"{proj.get('init_date', '?')}) blended with "
            f"{proj.get('days_in', '?')} days of month-to-date observations; "
            "interval widths include verified model-error terms and are "
            "capped against overconfidence while the verification archive "
            "is short.")
    else:
        method_note = (
            f"Projection: regression of full-{month_name} means on "
            "month-to-date means across all prior years (EC46 blend "
            "unavailable for this file); the p05/p95 columns are +/-2 sigma "
            "of the regression residuals.")
    _write(out, "monthly_projection.csv",
           f"{month_name} global mean anomaly by year, with the "
           f"{month_name} {year} projection (ERA5)",
           ["Anomalies vs preindustrial 1850-1900.", method_note,
            "The current year's monthly_mean_c is left blank (incomplete "
            "month); its month-to-date and projection ride in their own "
            "columns."])


def export_annual_prediction(df: pd.DataFrame, enso_df=None) -> None:
    """Annual anomaly & prediction panel. The regression + Monte Carlo lives
    inside the plot function, so extract the plotted traces — this guarantees
    the CSV matches the figure."""
    from src.dashboard import create_annual_prediction_plot

    fig = create_annual_prediction_plot(df, enso_df, dark_mode=False)
    obs = next((t for t in fig.data if (t.name or "") == "Observed"), None)
    ytd = next((t for t in fig.data if "YTD" in (t.name or "")), None)
    proj = next((t for t in fig.data if "projection" in (t.name or "")), None)
    if obs is None or len(obs.x) < 30:
        raise RuntimeError("annual prediction figure missing Observed trace")

    out = pd.DataFrame({"year": np.asarray(obs.x, dtype=int),
                        "annual_mean_c": np.asarray(obs.y, dtype=float)})
    extra = {}
    if ytd is not None:
        extra["year"] = int(ytd.x[0])
        extra["ytd_mean_c"] = float(ytd.y[0])
    if proj is not None:
        extra["year"] = int(proj.x[0])
        extra["projected_c"] = float(proj.y[0])
        up = float(np.asarray(proj.error_y["array"])[0])
        down = float(np.asarray(proj.error_y["arrayminus"])[0])
        extra["projection_lo_c"] = extra["projected_c"] - down
        extra["projection_hi_c"] = extra["projected_c"] + up
    if extra:
        out = pd.concat([out, pd.DataFrame([extra])], ignore_index=True)
    _write(out, "annual_prediction.csv",
           "Annual global mean anomaly and current-year prediction (ERA5)",
           ["Anomalies vs preindustrial 1850-1900; complete calendar years "
            "plus the current year's year-to-date mean and projection.",
            "Projection: regression on year, prior-year anomaly, observed/"
            "forecast ENSO, trailing-30-day and year-to-date anomalies; the "
            "lo/hi interval is a 95% Monte Carlo range over the ENSO "
            "multi-model ensemble plus regression residuals."])


def export_rank_probabilities(stats: dict) -> None:
    """Ranking-probabilities table (uses the already-computed stats dict)."""
    probs = stats.get("annual_rank_probs") or []
    if not probs:
        logger.warning("No annual rank probabilities to export")
        return
    out = pd.DataFrame(probs)[["rank", "rank_label", "prob",
                               "holder_year", "holder_value"]]
    out = out.rename(columns={"prob": "probability",
                              "holder_value": "holder_value_c"})
    _write(out, "rank_probabilities.csv",
           f"Where {stats.get('current_year', '')} likely ranks — final-rank "
           "probabilities from the Monte Carlo ensemble",
           ["probability is the fraction of Monte Carlo draws (ENSO "
            "multi-model ensemble plus regression residuals) landing at "
            "each final rank; rank 1 = warmest on record.",
            "holder_year / holder_value_c: the year currently holding that "
            "rank and its annual anomaly (degC vs preindustrial 1850-1900)."],
           float_format="%.4f")


def export_projection_history(df: pd.DataFrame) -> None:
    """How the projection has evolved: pass through the history file."""
    import sys
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
    from config import DATA_DIR

    year = int(df["year"].max())
    path = DATA_DIR / f"projection_history_{year}.csv"
    if not path.exists():
        logger.warning(f"{path.name} not found; skipping export")
        return
    h = pd.read_csv(path)
    out = pd.DataFrame({
        "date": h["date"],
        "projected_annual_c": h["prediction"],
        "sigma_c": h["uncertainty"],
        "ci95_lo_c": h["prediction"] - 2 * h["uncertainty"],
        "ci95_hi_c": h["prediction"] + 2 * h["uncertainty"],
        "ytd_mean_c": h["ytd_anomaly"],
    })
    _write(out, "projection_history.csv",
           f"How the {year} annual projection has evolved (daily)",
           ["Each row is the projection issued on that date, from data "
            "available through that date; anomalies vs preindustrial "
            "1850-1900.",
            "ci95 columns are the projection +/- 2 sigma."])


