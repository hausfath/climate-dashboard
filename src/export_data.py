def generate_all_csv_exports(df: pd.DataFrame, enso_df=None,
                             stats: dict | None = None) -> None:
    """Regenerate every downloadable CSV. Each step fails independently so
    one bad source never blocks the rest (mirrors the static-image flow)."""

    def _step(fn, *args, **kwargs):
        try:
            fn(*args, **kwargs)
        except Exception as e:
            logger.error(f"CSV export {fn.__name__} failed: {e}")

    _step(export_timeseries, df)
    _step(export_year_context, df)
    _step(export_monthly_projection, df)
    _step(export_annual_prediction, df, enso_df)
    _step(export_projection_history, df)
    _step(export_heatmaps, df)

    if stats is None:
        try:
            from src.dashboard import create_statistics_cards
            stats = create_statistics_cards(df)
        except Exception as e:
            logger.error(f"Stats for rank probabilities failed: {e}")
            stats = None
    if stats:
        _step(export_rank_probabilities, stats)

    _step(export_nino_daily_years)

    try:
        from src.enso_plots import load_enso_forecast_data
        ef, eo, _ = load_enso_forecast_data()
        if not ef.empty:
            for idx in _ENSO_INDEX_MODES:
                _step(export_enso_plume, ef, eo, idx)
                _step(export_enso_members, ef, idx)
                _step(export_enso_strength_probs, ef, idx)
                _step(export_enso_historical, idx)
    except Exception as e:
        logger.error(f"ENSO CSV exports failed: {e}")

    try:
        from src.models_vs_obs import load_cmip_ensemble, load_obs_data
        obs = load_obs_data()
        for gen in ("cmip3", "cmip5", "cmip6"):
            cmip = load_cmip_ensemble(gen)
            if cmip.empty:
                continue
            for baseline in _MODEL_BASELINES:
                _step(export_models_timeseries, cmip, obs, gen, baseline)
            _step(export_models_trends, cmip, obs, gen)
            _step(export_models_trend_members, cmip, obs, gen)
    except Exception as e:
        logger.error(f"Models CSV exports failed: {e}")

    logger.info("All CSV exports complete")


