_NINO_REGION_TITLES = {"nino12": "Nino 1+2", "nino3": "Nino 3",
                       "nino34": "Nino 3.4", "nino4": "Nino 4"}


def export_nino_daily_years() -> None:
    """Daily year-lines figure: one long-format file per region (ONI
    convention) plus the RONI variant (Niño 3.4 only, by definition).

    Deliberately imports only src.nino_daily (no plotting stack) so the
    lightweight afternoon OISST cron can refresh these files too."""
    from src.nino_daily import (era_relative_anomalies as
                                _era_relative_anomalies,
                                load_nino34_history)

    hist = load_nino34_history()
    base_notes = [
        "Anomalies vs centered 30-year day-of-year climatologies (the ONI "
        "convention: each year measured against its own era, windows "
        "clamped at the record edges, current year excluded), so the "
        "warming trend is removed and years compare as ENSO states.",
        "Feb 29 values are mapped to day-of-year 59 (Feb 28) so years align.",
        "Source: NOAA OISST v2.1 daily box means."]

    for region in ("nino34", "nino12", "nino3", "nino4"):
        d = _era_relative_anomalies(hist, "oni", region=region)
        if d is None or d.empty:
            logger.warning(f"No daily data for region {region}; skipping")
            continue
        out = d[["date", "year", "doy", "anom"]].rename(
            columns={"doy": "day_of_year", "anom": "anomaly_c"})
        out["date"] = pd.to_datetime(out["date"]).dt.strftime("%Y-%m-%d")
        _write(out, f"nino_daily_years_{region}.csv",
               f"This year vs every year since 1982 — daily "
               f"{_NINO_REGION_TITLES[region]} SST anomaly", base_notes,
               float_format="%.3f")

    d = _era_relative_anomalies(hist, "roni")
    if d is not None and not d.empty:
        out = d[["date", "year", "doy", "anom"]].rename(
            columns={"doy": "day_of_year", "anom": "anomaly_c"})
        out["date"] = pd.to_datetime(out["date"]).dt.strftime("%Y-%m-%d")
        _write(out, "nino_daily_years_roni.csv",
               "This year vs every year since 1982 — daily RONI "
               "(relative Nino 3.4)",
               ["RONI: Nino 3.4 anomaly minus the tropical-mean (20S-20N) "
                "SST anomaly, scaled by L'Heureux et al. monthly factors."]
               + base_notes, float_format="%.3f")

    # Absolute-SST variants (the figure's Anomaly/Absolute toggle)
    from src.nino_daily import FIRST_NINO_YEAR, _doy_key
    for region in ("nino34", "nino12", "nino3", "nino4"):
        if region not in hist.columns:
            continue
        d = hist.copy()
        d["year"] = d["date"].dt.year
        d["day_of_year"] = _doy_key(pd.DatetimeIndex(d["date"]))
        d = d[d["year"] >= FIRST_NINO_YEAR].dropna(subset=[region])
        out = d[["date", "year", "day_of_year", region]].rename(
            columns={region: "sst_c"})
        out["date"] = pd.to_datetime(out["date"]).dt.strftime("%Y-%m-%d")
        _write(out, f"nino_daily_years_{region}_abs.csv",
               f"This year vs every year since 1982 — daily "
               f"{_NINO_REGION_TITLES[region]} absolute SST",
               ["Raw daily box-mean SST (degC), seasonal cycle retained.",
                "Feb 29 values are mapped to day-of-year 59 (Feb 28) so "
                "years align.",
                "Source: NOAA OISST v2.1 daily box means."],
               float_format="%.3f")


def _prep_mega(forecast_df, index_mode):
    """Shared prep: swap the index column in and build the deduplicated
    member/mean frames, filtered to months with >=4 models (as plotted)."""
    from src.enso_plots import (_build_mega_df, _get_forecast_only,
                                _index_meta, _swap_to_nino34)
    meta = _index_meta(index_mode)
    fdf = _swap_to_nino34(forecast_df, meta["col"])
    mega = _build_mega_df(_get_forecast_only(fdf))
    members = mega[mega["member_id"] != "mean"].copy()
    means = mega[mega["member_id"] == "mean"].copy()
    models_per_month = means.groupby("target_month")["model"].nunique()
    valid = models_per_month[models_per_month >= 4].index
    return (members[members["target_month"].isin(valid)].copy(),
            means[means["target_month"].isin(valid)].copy(), meta)


def _idx_label(index_mode):
    return "RONI (relative Nino 3.4)" if index_mode == "roni" else \
        "ONI (Nino 3.4)"


def export_enso_plume(forecast_df, obs_df, index_mode="oni") -> None:
    """Combined forecast plume: weighted percentile fan, per-model ensemble
    means, multi-model median, and recent observed values."""
    from src.enso_plots import (_multimodel_weighted_median, _swap_to_nino34,
                                _target_month_to_date, _weighted_quantile)

    members, means, meta = _prep_mega(forecast_df, index_mode)
    if members.empty:
        logger.warning(f"No plume members for {index_mode}; skipping")
        return

    rows = []
    for tm in sorted(members["target_month"].unique()):
        tm_m = members[members["target_month"] == tm]
        counts = tm_m.groupby("model").size()
        w = tm_m["model"].map(lambda m: 1.0 / counts[m]).values
        v = tm_m["nino34_anom"].values
        mask = ~np.isnan(v)
        if mask.sum() == 0:
            continue
        rows.append({"target_month": tm,
                     **{f"p{int(q * 100):02d}":
                        _weighted_quantile(v[mask], w[mask], q)
                        for q in (0.05, 0.25, 0.75, 0.95)}})
    fan = pd.DataFrame(rows).set_index("target_month")

    mm = _multimodel_weighted_median(members).set_index("target_month")
    fan["multimodel_median_c"] = mm["nino34_anom"]

    model_means = means.pivot_table(index="target_month", columns="model",
                                    values="nino34_anom", aggfunc="first")
    model_means.columns = [f"mean_{m}" for m in model_means.columns]
    out = fan.join(model_means)

    if obs_df is not None and not obs_df.empty:
        odf = _swap_to_nino34(obs_df, meta["col"]).copy()
        odf["target_month"] = (pd.to_datetime(odf["date"])
                               .dt.to_period("M").astype(str))
        obs_series = odf.set_index("target_month")["nino34_anom"]
        obs_series = obs_series[~obs_series.index.duplicated(keep="last")]
        out = out.join(obs_series.rename("observed_c"), how="outer")
        out = out[out.index >= "2025-12"]

    out = out.sort_index().reset_index()
    label = _idx_label(index_mode)
    _write(out, f"enso_plume_{index_mode}.csv",
           f"Combined ENSO forecast plume — {label}",
           ["p05/p25/p75/p95: model-weighted percentiles across all "
            "ensemble members (each model weighted equally regardless of "
            "ensemble size); months with fewer than 4 models are dropped.",
            "mean_<model>: that model's ensemble-mean forecast; "
            "multimodel_median_c: the model-weighted median (forecast only, "
            "no observed substitution); observed_c: observed monthly index.",
            "Member-level values are in enso_members_" + index_mode + ".csv."])


def export_enso_members(forecast_df, index_mode="oni") -> None:
    """Monthly forecast distribution: every ensemble member value."""
    members, _, _ = _prep_mega(forecast_df, index_mode)
    if members.empty:
        logger.warning(f"No members for {index_mode}; skipping")
        return
    cols = ["target_month", "model", "member_id", "nino34_anom"]
    if "init_date" in members.columns:
        cols.insert(3, "init_date")
    out = (members[cols]
           .rename(columns={"nino34_anom": "anomaly_c"})
           .sort_values(["target_month", "model", "member_id"]))
    label = _idx_label(index_mode)
    _write(out, f"enso_members_{index_mode}.csv",
           f"ENSO forecast ensemble members — {label}",
           ["One row per ensemble member per target month (deduplicated "
            "multi-model plume; months with fewer than 4 models dropped).",
            "Dashboard statistics weight each model equally regardless of "
            "ensemble size. CFSv2 member ens_E3_041 is the control run and "
            "is excluded from the dashboard's probability statistics."])


def export_enso_strength_probs(forecast_df, index_mode="oni") -> None:
    """Strength probabilities by season."""
    from src.enso_plots import (STRENGTH_BINS, _season_label,
                                compute_strength_probabilities)

    centers, probs, n_models = compute_strength_probabilities(
        forecast_df, index_mode=index_mode)
    if not len(centers):
        logger.warning(f"No strength probabilities for {index_mode}")
        return
    colnames = [b[0].lower().replace(" ", "_")
                .replace("ñ", "n") + "_pct" for b in STRENGTH_BINS]
    out = pd.DataFrame(probs, columns=colnames)
    out.insert(0, "season", [_season_label(c) for c in centers])
    out.insert(1, "season_center", [c.strftime("%Y-%m") for c in centers])
    out["n_models"] = n_models
    label = _idx_label(index_mode)
    _write(out, f"enso_strength_probs_{index_mode}.csv",
           f"ENSO strength probabilities by season — {label}",
           ["Model-weighted category probabilities (percent) per "
            "overlapping 3-month season, from the multi-model ensemble; "
            "observed months are blended into seasonal means where "
            "available.",
            "Categories use ONI event thresholds (0.5/1.0/1.5/2.0 degC).",
            "n_models: number of forecast systems contributing to that "
            "season."], float_format="%.2f")


def export_enso_historical(index_mode="oni") -> None:
    """Historical record + current forecast panel (observed monthly series
    back to 1990, multi-model weighted median forecast with 25-75% band)."""
    from src.enso_plots import (_build_mega_df, _get_forecast_only,
                                _index_meta, _multimodel_weighted_median,
                                _swap_to_nino34, _target_month_to_date,
                                _weighted_quantile, load_enso_forecast_data,
                                load_full_observed)
    from src.enso_skill import _load_observed_oisst

    meta = _index_meta(index_mode)
    forecast_df, _, _ = load_enso_forecast_data()

    obs_full = load_full_observed(start_year=1990)
    obs_full = _swap_to_nino34(obs_full, meta["col"])
    fdf = _swap_to_nino34(forecast_df, meta["col"])
    obs_full = obs_full.dropna(subset=["nino34_anom"]).reset_index(drop=True)

    # Overlay OISSTv2.1 monthly means (complete months only), as the chart's
    # observed truth does.
    try:
        oisst = _load_observed_oisst(index_mode, start="1990-01-01")
    except Exception:
        oisst = pd.DataFrame()
    if not oisst.empty:
        oisst_map = oisst.set_index("date")["value"]
        obs_full = obs_full.set_index("date")
        overlap = obs_full.index.intersection(oisst_map.index)
        obs_full.loc[overlap, "nino34_anom"] = oisst_map[overlap]
        new_months = oisst_map.index.difference(obs_full.index)
        if len(new_months):
            add = pd.DataFrame({"date": new_months,
                                "nino34_anom": oisst_map[new_months].values})
            obs_full = pd.concat([obs_full.reset_index(), add],
                                 ignore_index=True).set_index("date")
        obs_full = obs_full.sort_index().reset_index()

    obs_lookup = obs_full.set_index(
        obs_full["date"].dt.to_period("M").astype(str))["nino34_anom"]

    forecast_only = _get_forecast_only(fdf)
    mega = _build_mega_df(forecast_only)
    means = mega[mega["member_id"] == "mean"].copy()
    fc_members = mega[mega["member_id"] != "mean"].copy()
    models_per_month = means.groupby("target_month")["model"].nunique()
    valid_months = models_per_month[models_per_month >= 4].index
    fc_members = fc_members[fc_members["target_month"].isin(valid_months)]

    mm = _multimodel_weighted_median(fc_members)
    mm["date"] = mm["target_month"].apply(_target_month_to_date)
    for idx, row in mm.iterrows():
        if row["target_month"] in obs_lookup.index:
            mm.loc[idx, "nino34_anom"] = obs_lookup[row["target_month"]]

    q25_map, q75_map = {}, {}
    for tm in sorted(mm["target_month"].unique()):
        if tm in obs_lookup.index:
            q25_map[tm] = q75_map[tm] = float(obs_lookup[tm])
            continue
        tm_members = fc_members[fc_members["target_month"] == tm]
        vals = tm_members["nino34_anom"].values
        valid = ~np.isnan(vals)
        if tm_members.empty or valid.sum() == 0:
            q25_map[tm] = q75_map[tm] = np.nan
            continue
        counts = tm_members.groupby("model").size()
        w = tm_members["model"].map(lambda m: 1.0 / counts[m]).values
        q25_map[tm] = _weighted_quantile(vals[valid], w[valid], 0.25)
        q75_map[tm] = _weighted_quantile(vals[valid], w[valid], 0.75)

    fc_rows = []
    for _, row in mm.sort_values("date").iterrows():
        tm = row["target_month"]
        fc_rows.append({
            "date": row["date"].strftime("%Y-%m-%d"),
            "is_forecast": tm not in obs_lookup.index,
            "observed_c": (float(obs_lookup[tm])
                           if tm in obs_lookup.index else np.nan),
            "forecast_median_c": float(row["nino34_anom"]),
            "forecast_q25_c": q25_map.get(tm, np.nan),
            "forecast_q75_c": q75_map.get(tm, np.nan),
            "n_models": int(models_per_month.get(tm, 0)),
        })
    fc_df = pd.DataFrame(fc_rows)

    fc_months = set(pd.to_datetime(fc_df["date"]).dt.strftime("%Y-%m"))
    pre_rows = []
    for _, row in obs_full.iterrows():
        if row["date"].strftime("%Y-%m") in fc_months:
            continue
        pre_rows.append({"date": row["date"].strftime("%Y-%m-%d"),
                         "is_forecast": False,
                         "observed_c": float(row["nino34_anom"]),
                         "forecast_median_c": np.nan,
                         "forecast_q25_c": np.nan,
                         "forecast_q75_c": np.nan,
                         "n_models": 0})
    full = (pd.concat([pd.DataFrame(pre_rows), fc_df], ignore_index=True)
            .sort_values("date").reset_index(drop=True))

    label = _idx_label(index_mode)
    _write(full, f"enso_historical_{index_mode}.csv",
           f"Historical ENSO record and current forecast — {label}",
           ["Observed monthly index back to 1990 (NOAA, with OISSTv2.1 "
            "monthly means overlaid for recent months), plus the "
            "multi-model weighted-median forecast with its 25th-75th "
            "percentile band (months with fewer than 4 models dropped).",
            "Forecast months that already verify are shown as observed "
            "(is_forecast=False)."])


