"""Per-plot CSV exports for the Climate Dashboard.

Every figure panel on the dashboard carries a "Download CSV" link pointing
at a file under ``assets/data/`` that contains exactly the data plotted,
regenerated by the daily update pipeline (``run.py update``). Filenames are
stable so links never break; each file starts with ``#`` comment lines
documenting the source, baseline, and units (always °C). Read with
``pandas.read_csv(path, comment='#')``.

Toggle states that change the plotted data map to separate files (e.g.
``enso_plume_oni.csv`` / ``enso_plume_roni.csv``); toggles that only
restyle the figure (dark mode, °C/°F display, static/interactive) do not.
"""

import logging
from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd

logger = logging.getLogger(__name__)

CSV_DIR = Path(__file__).resolve().parent.parent / "assets" / "data"

_REPO = "https://github.com/hausfath/climate-dashboard"

# Kept in sync with the highlighted years in the daily context plots
_ENSO_INDEX_MODES = ("oni", "roni")


def _write(df: pd.DataFrame, filename: str, title: str, notes=(),
           float_format: str = "%.4f", index: bool = False) -> None:
    """Write ``df`` to assets/data/<filename> with a commented header.

    If nothing but the generation-date stamp changed, the existing file is
    left untouched so unchanged datasets don't churn in git every day.
    """
    CSV_DIR.mkdir(parents=True, exist_ok=True)
    path = CSV_DIR / filename
    stamp_line = (f"# Climate Dashboard ({_REPO}) — regenerated daily; "
                  f"this file: {date.today().isoformat()}")
    lines = [f"# {title}", stamp_line]
    lines += [f"# {n}" for n in notes]
    lines.append("# All values in degrees Celsius unless a column "
                 "says otherwise. Load with pandas.read_csv(..., comment='#').")
    content = "\n".join(lines) + "\n" + df.to_csv(
        index=index, float_format=float_format)

    if path.exists():
        old = path.read_text()
        strip = lambda s: "\n".join(
            l for l in s.splitlines() if not l.startswith("# Climate Dashboard"))
        if strip(old) == strip(content):
            logger.info(f"{path.name} unchanged; kept existing file")
            return
    path.write_text(content)
    logger.info(f"Wrote {path.name} ({len(df)} rows)")


